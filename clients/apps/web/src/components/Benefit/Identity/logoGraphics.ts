import type { GraphicRenderer } from './BenefitGraphic'

/**
 * Outlined brand logos (Discord, GitHub, Slack) drawn as thin strokes
 * with a bright dash highlight traveling along the outline — the same
 * rail/trail treatment as the landing page graphics.
 */

interface LogoSpec {
  view: { x: number; y: number; w: number; h: number }
  paths: string[]
}

const makeLogoRenderer = (spec: LogoSpec): GraphicRenderer => {
  let cached: Path2D[] | null = null

  return (ctx, size, elapsed, colors) => {
    cached ??= spec.paths.map((d) => new Path2D(d))

    const fit = (size * 0.72) / Math.max(spec.view.w, spec.view.h)
    const tx = (size - spec.view.w * fit) / 2 - spec.view.x * fit
    const ty = (size - spec.view.h * fit) / 2 - spec.view.y * fit

    ctx.save()
    ctx.translate(tx, ty)
    ctx.scale(fit, fit)

    ctx.strokeStyle = colors.dim
    ctx.lineWidth = 2 / fit
    ctx.setLineDash([])
    cached.forEach((p) => ctx.stroke(p))

    // Bright dash segments drifting along the outline. `source-atop`
    // confines them to the dim rail already painted.
    const unit = spec.view.w
    ctx.globalCompositeOperation = 'source-atop'
    ctx.strokeStyle = colors.stroke
    ctx.lineWidth = 2.5 / fit
    ctx.setLineDash([unit * 0.55, unit * 2.2])
    ctx.lineDashOffset = -(elapsed * unit * 0.35)
    cached.forEach((p) => ctx.stroke(p))

    ctx.globalCompositeOperation = 'source-over'
    ctx.setLineDash([])
    ctx.restore()
  }
}

