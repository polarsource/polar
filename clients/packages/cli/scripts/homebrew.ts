import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'

const archives = [
  'polar-darwin-arm64.zip',
  'polar-darwin-x64.zip',
  'polar-linux-x64.tar.gz',
  'polar-linux-arm64.tar.gz',
] as const

export function generateFormula(tag: string, checksums: string): string {
  if (!/^@polar-sh\/cli@\d+\.\d+\.\d+$/.test(tag)) {
    throw new Error(
      'Homebrew requires a stable release tag, e.g. @polar-sh/cli@2.0.0',
    )
  }

  const hashes = new Map<string, string>()
  for (const line of checksums.trim().split(/\r?\n/)) {
    const match = /^([a-fA-F0-9]{64})\s+\*?(\S+)$/.exec(line)
    if (!match) throw new Error(`Invalid checksum entry: ${line}`)
    const [, hash, archive] = match
    if (!hash || !archive) throw new Error(`Invalid checksum entry: ${line}`)
    if (hashes.has(archive)) {
      throw new Error(`Duplicate checksum for ${archive}`)
    }
    hashes.set(archive, hash.toLowerCase())
  }
  for (const archive of archives) {
    if (!hashes.has(archive)) throw new Error(`Missing checksum for ${archive}`)
  }

  const url = `https://github.com/polarsource/polar/releases/download/${encodeURIComponent(tag)}`
  return `# Generated by polarsource/polar clients/packages/cli/scripts/homebrew.ts. Do not edit manually.
class Cli < Formula
  desc "Official command-line interface for Polar"
  homepage "https://polar.sh"
  version "${tag.slice('@polar-sh/cli@'.length)}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${url}/polar-darwin-arm64.zip"
      sha256 "${hashes.get(archives[0])}"
    end
    on_intel do
      url "${url}/polar-darwin-x64.zip"
      sha256 "${hashes.get(archives[1])}"
    end
  end

  on_linux do
    on_arm do
      url "${url}/polar-linux-arm64.tar.gz"
      sha256 "${hashes.get(archives[3])}"
    end
    on_intel do
      url "${url}/polar-linux-x64.tar.gz"
      sha256 "${hashes.get(archives[2])}"
    end
  end

  def install
    bin.install "polar"
  end

  test do
    assert_match "polar", shell_output("#{bin}/polar --help")
    assert_match(/\\d+\\.\\d+\\.\\d+/, shell_output("#{bin}/polar --version"))
  end
end
`
}

if (import.meta.main) {
  const [tag, checksumsPath, outputPath] = process.argv.slice(2)
  if (!tag || !checksumsPath || !outputPath) {
    throw new Error(
      'Usage: bun scripts/homebrew.ts TAG CHECKSUMS_PATH OUTPUT_PATH',
    )
  }
  const formula = generateFormula(tag, await readFile(checksumsPath, 'utf8'))
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, formula)
}
