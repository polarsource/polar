import { describe, expect, test } from 'vitest'
import {
  GENERATED_LANGUAGES,
  GENERATORS,
} from '@/services/billing-config/generate'
import {
  generate,
  isGenerated,
  sectionsOf,
} from '@/services/billing-config/generate/contract'
import { python } from '@/services/billing-config/generate/python'

const NONE = {
  events: [],
  anyEvent: false,
  meters: [],
  benefits: [],
  products: [],
}

const CONFIG = {
  meters: [
    {
      external_id: 'tool-calls',
      filter: {
        clauses: [{ property: 'name', operator: 'eq', value: 'tool.call' }],
      },
    },
  ],
  benefits: [{ external_id: 'custom_servers' }],
  products: [{ external_id: 'pro' }, { external_id: 'team:yearly' }],
}

const constants = (ids: ReadonlyArray<string>, reserved: Array<string> = []) =>
  sectionsOf({ ...NONE, benefits: ids }, new Set(reserved))
    .find(({ group }) => group === 'Benefits')!
    .constants.map(({ name, value }) => [name, value])

describe('sectionsOf', () => {
  test('gives every language the same groups, types and names', () => {
    expect(
      sectionsOf(
        {
          events: ['tool.call'],
          anyEvent: false,
          meters: ['tool-calls'],
          benefits: [],
          products: ['pro'],
        },
        new Set(),
      ),
    ).toEqual([
      {
        group: 'Events',
        type: 'EventName',
        description: 'The names of the events the meters in the config count.',
        constants: [{ name: 'tool_call', value: 'tool.call' }],
        open: false,
      },
      {
        group: 'Meters',
        type: 'ExternalMeterId',
        description: 'The external IDs of the meters in the config.',
        constants: [{ name: 'tool_calls', value: 'tool-calls' }],
        open: false,
      },
      {
        group: 'Benefits',
        type: 'ExternalBenefitId',
        description: 'The external IDs of the benefits in the config.',
        constants: [],
        open: false,
      },
      {
        group: 'Products',
        type: 'ExternalProductId',
        description: 'The external IDs of the products in the config.',
        constants: [{ name: 'pro', value: 'pro' }],
        open: false,
      },
    ])
  })

  test('leaves only the event names open when a meter counts any event', () => {
    expect(
      sectionsOf({ ...NONE, anyEvent: true }, new Set()).map(
        ({ group, open }) => [group, open],
      ),
    ).toEqual([
      ['Events', true],
      ['Meters', false],
      ['Benefits', false],
      ['Products', false],
    ])
  })

  test.each([
    [
      'an ID that is a valid name keeps it, whatever comes first',
      ['topup-100', 'topup_100'],
      [
        ['topup_100_2', 'topup-100'],
        ['topup_100', 'topup_100'],
      ],
    ],
    [
      'IDs that would share a name are numbered in the order of the IDs',
      ['a.b', 'a-b', 'a:b'],
      [
        ['a_b_2', 'a.b'],
        ['a_b', 'a-b'],
        ['a_b_3', 'a:b'],
      ],
    ],
    [
      'names the language reserves, or that start with a digit, get a prefix',
      ['class', 'id_class', '9lives'],
      [
        ['id_class_2', 'class'],
        ['id_class', 'id_class'],
        ['id_9lives', '9lives'],
      ],
    ],
  ])('%s', (_, ids, expected) => {
    expect(constants(ids, ['class'])).toEqual(expected)
    expect(constants(ids.toReversed(), ['class'])).toEqual(
      expected.toReversed(),
    )
  })
})

describe('generate', () => {
  test('writes the names of a config under a header that says where they came from', () => {
    expect(
      generate(
        { benefits: [{ external_id: 'pro' }] },
        python,
        'polar.config.json',
      ).split('\n', 6),
    ).toEqual([
      '# Generated by polar config generate from polar.config.json. Do not edit.',
      '# fmt: off',
      '# ruff: noqa',
      '# flake8: noqa',
      '# pylint: skip-file',
      '',
    ])
  })

  test('keeps a file name from adding lines to the header', () => {
    const [header, directive] = generate(
      {},
      python,
      'polar\nimport os\n.json',
    ).split('\n')

    expect(header).toBe(
      '# Generated by polar config generate from polar?import os?.json. Do not edit.',
    )
    expect(directive).toBe('# fmt: off')
  })

  test('only calls a file its own when it starts with the header', () => {
    const mentioned =
      '"""Replaces what was Generated by polar config generate."""'

    expect(isGenerated(generate({}, python, 'polar.config.json'), python)).toBe(
      true,
    )
    expect(isGenerated(mentioned, python)).toBe(false)
  })
})

describe.each(GENERATED_LANGUAGES)('the %s generator', (language) => {
  const generator = GENERATORS[language]

  test('renders every group, type and name of the contract', () => {
    const source = generate(CONFIG, generator, 'polar.config.json')

    for (const { group, type, constants } of sectionsOf(
      {
        events: ['tool.call'],
        anyEvent: false,
        meters: ['tool-calls'],
        benefits: ['custom_servers'],
        products: ['pro', 'team:yearly'],
      },
      generator.reserved,
    )) {
      expect(source).toContain(group)
      expect(source).toContain(type)
      for (const { name, value } of constants) {
        expect(source).toContain(name)
        expect(source).toContain(JSON.stringify(value))
      }
    }
  })

  test('recognises the file it writes as generated', () => {
    expect(isGenerated(generate({}, generator, 'polar.json'), generator)).toBe(
      true,
    )
  })
})
