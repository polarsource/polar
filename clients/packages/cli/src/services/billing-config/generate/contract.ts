import { type Names, namesOf } from '@/services/billing-config/generate/names'

export interface Constant {
  readonly name: string
  readonly value: string
}

export interface Section {
  readonly group: string
  readonly type: string
  readonly description: string
  readonly constants: ReadonlyArray<Constant>
  readonly open: boolean
}

export interface Generator {
  readonly title: string
  readonly file: string
  readonly manifests: ReadonlyArray<string>
  readonly comment: string
  readonly directives: ReadonlyArray<string>
  readonly reserved: ReadonlySet<string>
  readonly render: (sections: ReadonlyArray<Section>) => string
}

const SECTIONS = [
  {
    names: 'events',
    group: 'Events',
    type: 'EventName',
    description: 'The names of the events the meters in the config count.',
  },
  {
    names: 'meters',
    group: 'Meters',
    type: 'ExternalMeterId',
    description: 'The external IDs of the meters in the config.',
  },
  {
    names: 'benefits',
    group: 'Benefits',
    type: 'ExternalBenefitId',
    description: 'The external IDs of the benefits in the config.',
  },
  {
    names: 'products',
    group: 'Products',
    type: 'ExternalProductId',
    description: 'The external IDs of the products in the config.',
  },
] as const satisfies ReadonlyArray<
  Omit<Section, 'constants' | 'open'> & {
    readonly names: Exclude<keyof Names, 'anyEvent'>
  }
>

const constantsOf = (
  values: ReadonlyArray<string>,
  reserved: ReadonlySet<string>,
): ReadonlyArray<Constant> => {
  const isName = (name: string) =>
    /^[A-Za-z][A-Za-z0-9_]*$/.test(name) && !reserved.has(name)
  const taken = new Set(values.filter(isName))
  const names = new Map<string, string>()
  for (const value of values.filter((value) => !isName(value)).toSorted()) {
    const base = value.replaceAll(/\W/g, '_').replace(/^_+/, '')
    const wanted = isName(base) ? base : `id_${base}`
    let name = wanted
    for (let count = 2; taken.has(name); count++) {
      name = `${wanted}_${count}`
    }
    taken.add(name)
    names.set(value, name)
  }
  return values.map((value) => ({ name: names.get(value) ?? value, value }))
}

export const sectionsOf = (
  names: Names,
  reserved: ReadonlySet<string>,
): ReadonlyArray<Section> =>
  SECTIONS.map(({ names: key, ...section }) => ({
    ...section,
    constants: constantsOf(names[key], reserved),
    open: key === 'events' && names.anyEvent,
  }))

const marker = ({ comment }: Generator) =>
  `${comment} Generated by polar config generate`

export const isGenerated = (source: string, generator: Generator) =>
  source.startsWith(marker(generator))

export const generate = (
  input: unknown,
  generator: Generator,
  configFile: string,
) => {
  const { comment, directives, reserved, render } = generator
  const from = configFile.replaceAll(/[^\x20-\x7E]/g, '?')
  return [
    `${marker(generator)} from ${from}. Do not edit.`,
    ...directives.map((directive) => `${comment} ${directive}`),
    '',
    render(sectionsOf(namesOf(input), reserved)),
    '',
  ].join('\n')
}
