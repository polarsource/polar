import { describe, expect, test } from 'vitest'
import { generate } from '@/utils/billing-config/generate'

describe('generate', () => {
  test('writes the names of a config under a header that says where they came from', () => {
    expect(
      generate(
        { benefits: [{ external_id: 'pro' }] },
        'py',
        'polar.config.json',
      ),
    )
      .toBe(`# Generated by polar config generate from polar.config.json. Do not edit.
# fmt: off
# ruff: noqa

import typing


class Events:
    pass


EventName = typing.Never


class Meters:
    pass


MeterId = typing.Never


class Benefits:
    pro: typing.Final = "pro"


BenefitId = typing.Literal["pro"]


class Products:
    pass


ProductId = typing.Never
`)
  })

  test('keeps a file name from adding lines to the header', () => {
    const [header, directive] = generate(
      {},
      'py',
      'polar\nimport os\n.json',
    ).split('\n')

    expect(header).toBe(
      '# Generated by polar config generate from polar?import os?.json. Do not edit.',
    )
    expect(directive).toBe('# fmt: off')
  })
})
