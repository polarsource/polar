import { namesOf } from '@/utils/billing-config/generate/names'
import { python } from '@/utils/billing-config/generate/python'

export const GENERATED_MARKER = 'Generated by polar config generate'

export const GENERATORS = { py: python } as const

export type GeneratedLanguage = keyof typeof GENERATORS

export const GENERATED_LANGUAGES = Object.keys(
  GENERATORS,
) as ReadonlyArray<GeneratedLanguage>

/** The names in a config, as a source file application code can import. */
export const generate = (
  input: unknown,
  language: GeneratedLanguage,
  configFile: string,
) => {
  const { comment, directives, render } = GENERATORS[language]
  const from = configFile.replaceAll(/[^\x20-\x7E]/g, '?')
  return [
    `${comment} ${GENERATED_MARKER} from ${from}. Do not edit.`,
    ...directives.map((directive) => `${comment} ${directive}`),
    '',
    render(namesOf(input)),
    '',
  ].join('\n')
}
