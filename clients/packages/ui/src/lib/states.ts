export const COUNTRIES_WITH_FIXED_STATE_OPTIONS =
  Object.keys(FIXED_STATE_OPTIONS)

export const hasFixedStateOptions = (country?: string | null): boolean =>
  !!country && country in FIXED_STATE_OPTIONS

export const usesStateLabel = (country?: string | null): boolean =>
  !!country && STATE_LABEL_COUNTRIES.includes(country)

export const getStateLabel = (country?: string | null): string =>
  usesStateLabel(country) ? 'State' : 'Province'
