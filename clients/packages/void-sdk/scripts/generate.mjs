import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { promiseClientSource } from './promise-client.ts'

const sdk = fileURLToPath(new URL('..', import.meta.url))
const input = process.argv[2] ? resolve(process.argv[2]) : `${sdk}/openapi.json`
const openapi = readFileSync(input, 'utf8')
const promiseClient = promiseClientSource(JSON.parse(openapi))
writeFileSync(`${sdk}/openapi.json`, openapi)
const generated = execFileSync(
  `${sdk}/node_modules/.bin/openapigen`,
  ['-s', `${sdk}/openapi.json`, '-f', 'httpclient', '-n', 'VoidApi'],
  { encoding: 'utf8' },
)
writeFileSync(
  `${sdk}/src/api/generated.ts`,
  (
    '// Generated by `pnpm generate` from openapi.json. Do not edit.\n/* eslint-disable */\n' +
    generated +
    '\n' +
    promiseClient
  ).replace(/[ \t]+$/gm, ''),
)
