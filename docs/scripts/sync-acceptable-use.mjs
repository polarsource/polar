import { readFileSync, writeFileSync } from "node:fs";

const sourcePath = new URL(
  "../../clients/apps/web/src/app/(main)/(website)/(landing)/(mdx)/legal/acceptable-use-policy/page.mdx",
  import.meta.url,
);
const destinationPath = new URL(
  "../merchant-of-record/acceptable-use.mdx",
  import.meta.url,
);
const source = readFileSync(sourcePath, "utf8");
const policy = source.match(
  /^---\n[\s\S]*?\n---\n\s*<BlogHero\s+title="([^"]+)"\s+description="([^"]+)"\s*\/>\s*<InnerWrapper>\s*([\s\S]*?)\s*<\/InnerWrapper>\s*$/,
);

if (!policy) {
  throw new Error("The legal policy layout changed. Update the AUP sync script.");
}

const [, title, description, body] = policy;
const headings = [
  "Prohibited Activities",
  "Acceptable Products",
  "Prohibited Products",
  "Restricted businesses that require closer review",
];
const content = body
  .replace(/^\*\*([^\n]+)\*\*$/gm, (line, text) =>
    headings.includes(text) ? `## ${text}` : line,
  )
  .replace(
    /\]\(\/legal\/master-services-agreement\)/g,
    "](https://polar.sh/legal/master-services-terms)",
  )
  .replace(/\]\(\/legal\//g, "](https://polar.sh/legal/");
const generated = `---
title: ${JSON.stringify(title)}
sidebarTitle: "Acceptable use"
description: ${JSON.stringify(description)}
---

{/* Generated by pnpm sync:aup from the legal policy. */}

[View this policy on the Polar legal website](https://polar.sh/legal/acceptable-use-policy).

${content}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(destinationPath, "utf8") !== generated) {
    console.error("The docs policy is out of date. Run pnpm sync:aup in docs/.");
    process.exitCode = 1;
  } else {
    console.log("The docs policy matches the legal source.");
  }
} else {
  writeFileSync(destinationPath, generated);
  console.log("Updated merchant-of-record/acceptable-use.mdx.");
}
