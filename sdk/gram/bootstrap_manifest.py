#!/usr/bin/env python3
"""Generate a polar-mcp.yaml manifest from a Gram `toolsets.get` response.

This lets the committed manifest be verified against (or regenerated from) the
live MCP rather than hand-maintained. It reads the JSON body of
`GET /rpc/toolsets.get?slug=<toolset>` and prints an environment-agnostic
manifest: the exposed tool set plus the per-tool name/description overrides
that differ from the source OpenAPI operation.

Usage:
    # From a saved response:
    ./sdk/gram/bootstrap_manifest.py < toolset.get.json > sdk/gram/polar-mcp.yaml

    # Straight from the API (needs GRAM_API_KEY, GRAM_ORG optional, GRAM_PROJECT):
    curl -fsS "$GRAM_API_URL/rpc/toolsets.get?slug=polar" \
        -H "Gram-Key: $GRAM_API_KEY" -H "Gram-Project: $GRAM_PROJECT" \
      | ./sdk/gram/bootstrap_manifest.py

Only `title` and `description` overrides are emitted (the meaningful human
edits). Add hints/confirm/tags by hand if you start managing those too.
"""

from __future__ import annotations

import json
import sys


def _q(value: str) -> str:
    """Render a string as a safe YAML double-quoted scalar."""
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def _name(defn: dict, urn: str) -> str:
    name = defn.get("name")
    if name:
        return name
    return urn.rsplit(":", 1)[-1]


def build_manifest(toolset: dict) -> str:
    read_from = toolset.get("mcp_slug") or toolset.get("slug") or "unknown"

    tools = sorted({urn.rsplit(":", 1)[-1] for urn in toolset.get("tool_urns", [])})

    overrides: dict[str, dict[str, str]] = {}
    for entry in toolset.get("tools", []):
        defn = entry.get("http_tool_definition")
        if not defn:
            continue
        variation = defn.get("variation")
        if not variation:
            continue
        name = _name(defn, defn.get("tool_urn", ""))
        canonical = defn.get("canonical") or {}
        override: dict[str, str] = {}
        title = variation.get("title")
        if title:
            override["title"] = title
        description = variation.get("description")
        if description and description != canonical.get("description"):
            override["description"] = description
        if override:
            overrides[name] = override

    lines: list[str] = []
    lines.append("# Shared tools + overrides generated by sdk/gram/bootstrap_manifest.py")
    lines.append(f"# Read from Gram MCP: {read_from}")
    lines.append("# Diff against the `tools`/`overrides` in polar-mcp.yaml; `targets` are")
    lines.append("# maintained by hand and not emitted here.")
    lines.append("")
    lines.append(f"tools:  # {len(tools)} exposed tools")
    for name in tools:
        lines.append(f"  - {name}")
    lines.append("")
    lines.append("overrides:")
    for name in sorted(overrides):
        lines.append(f"  {name}:")
        for key in ("title", "description"):
            if key in overrides[name]:
                lines.append(f"    {key}: {_q(overrides[name][key])}")
    return "\n".join(lines) + "\n"


def main() -> None:
    raw = sys.stdin.read()
    if not raw.strip():
        sys.exit("no input: pipe a toolsets.get JSON body on stdin")
    toolset = json.loads(raw)
    sys.stdout.write(build_manifest(toolset))


if __name__ == "__main__":
    main()
