var (
	_ resource.Resource                = (*webhookEndpointResource)(nil)
	_ resource.ResourceWithConfigure   = (*webhookEndpointResource)(nil)
	_ resource.ResourceWithImportState = (*webhookEndpointResource)(nil)
)

func NewWebhookEndpointResource() resource.Resource {
	return &webhookEndpointResource{}
}

type webhookEndpointResource struct {
	client *polarapi.Client
}

type webhookEndpointModel struct {
	ID             types.String `tfsdk:"id"`
	URL            types.String `tfsdk:"url"`
	Name           types.String `tfsdk:"name"`
	Format         types.String `tfsdk:"format"`
	Events         types.List   `tfsdk:"events"`
	Enabled        types.Bool   `tfsdk:"enabled"`
	Secret         types.String `tfsdk:"secret"`
	OrganizationID types.String `tfsdk:"organization_id"`
	CreatedAt      types.String `tfsdk:"created_at"`
}

func (r *webhookEndpointResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_webhook_endpoint"
}

func (r *webhookEndpointResource) Schema(ctx context.Context, req resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "A webhook endpoint receiving events for the organization. " +
			"The signing secret is generated by Polar and exposed as the sensitive `secret` attribute.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				MarkdownDescription: "The ID of the webhook endpoint.",
				Computed:            true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
				},
			},
			"url": schema.StringAttribute{
				MarkdownDescription: "The HTTPS URL where webhook events are sent.",
				Required:            true,
				Validators: []validator.String{
					stringvalidator.RegexMatches(httpsURLRegex, "must be an https:// URL"),
				},
			},
			"name": schema.StringAttribute{
				MarkdownDescription: "An optional name to help identify the endpoint.",
				Optional:            true,
			},
			"format": schema.StringAttribute{
				MarkdownDescription: "The format of the webhook payload: `raw`, `discord` or `slack`.",
				Required:            true,
				Validators: []validator.String{
					stringvalidator.OneOf("raw", "discord", "slack"),
				},
			},
			"events": schema.ListAttribute{
				MarkdownDescription: "The event types delivered to this endpoint, e.g. `order.created`. " +
					"See the Polar webhook documentation for the full list.",
				Required:    true,
				ElementType: types.StringType,
				Validators: []validator.List{
					listvalidator.SizeAtLeast(1),
				},
			},
			"enabled": schema.BoolAttribute{
				MarkdownDescription: "Whether the endpoint receives events. Defaults to `true`.",
				Optional:            true,
				Computed:            true,
			},
			"secret": schema.StringAttribute{
				MarkdownDescription: "The secret used to sign webhook payloads. Generated by Polar.",
				Computed:            true,
				Sensitive:           true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
				},
			},
			"organization_id": schema.StringAttribute{
				MarkdownDescription: "The ID of the organization owning the endpoint. " +
					"Not needed when authenticating with an organization access token.",
				Optional: true,
				Computed: true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.RequiresReplace(),
					stringplanmodifier.UseStateForUnknown(),
				},
			},
			"created_at": schema.StringAttribute{
				MarkdownDescription: "Creation timestamp of the webhook endpoint.",
				Computed:            true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
				},
			},
		},
	}
}

func (r *webhookEndpointResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.client = configureClient(req.ProviderData, &resp.Diagnostics)
}

func (r *webhookEndpointResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan webhookEndpointModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	events, diags := eventsToAPI(ctx, plan.Events)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	endpoint, err := r.client.CreateWebhookEndpoint(ctx, polarapi.WebhookEndpointCreate{
		URL:            plan.URL.ValueString(),
		Name:           stringPointer(plan.Name),
		Format:         plan.Format.ValueString(),
		Events:         events,
		OrganizationID: stringPointer(plan.OrganizationID),
	})
	if err != nil {
		resp.Diagnostics.AddError("Failed to create webhook endpoint", err.Error())
		return
	}

	// The API always creates endpoints enabled; `enabled` only exists on
	// update. Honor an explicit `enabled = false` with a follow-up update.
	if !plan.Enabled.IsNull() && !plan.Enabled.IsUnknown() && !plan.Enabled.ValueBool() {
		disabled := false
		endpoint, err = r.client.UpdateWebhookEndpoint(ctx, endpoint.ID, polarapi.WebhookEndpointUpdate{
			Enabled: &disabled,
		})
		if err != nil {
			resp.Diagnostics.AddError(
				"Failed to disable webhook endpoint after creation",
				"The endpoint was created but disabling it failed, so it is currently enabled. Error: "+err.Error(),
			)
			return
		}
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, webhookEndpointToModel(ctx, endpoint))...)
}

func (r *webhookEndpointResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state webhookEndpointModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	endpoint, err := r.client.GetWebhookEndpoint(ctx, state.ID.ValueString())
	if err != nil {
		if polarapi.IsNotFound(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Failed to read webhook endpoint", err.Error())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, webhookEndpointToModel(ctx, endpoint))...)
}

func (r *webhookEndpointResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan webhookEndpointModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	events, diags := eventsToAPI(ctx, plan.Events)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	update := polarapi.WebhookEndpointUpdate{
		URL:     stringPointer(plan.URL),
		Name:    stringPointer(plan.Name),
		Format:  stringPointer(plan.Format),
		Events:  events,
		Enabled: boolPointer(plan.Enabled),
	}

	endpoint, err := r.client.UpdateWebhookEndpoint(ctx, plan.ID.ValueString(), update)
	if err != nil {
		resp.Diagnostics.AddError("Failed to update webhook endpoint", err.Error())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, webhookEndpointToModel(ctx, endpoint))...)
}

func (r *webhookEndpointResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state webhookEndpointModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if err := r.client.DeleteWebhookEndpoint(ctx, state.ID.ValueString()); err != nil && !polarapi.IsNotFound(err) {
		resp.Diagnostics.AddError("Failed to delete webhook endpoint", err.Error())
	}
}

func (r *webhookEndpointResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}

func webhookEndpointToModel(ctx context.Context, endpoint *polarapi.WebhookEndpoint) webhookEndpointModel {
	events, _ := types.ListValueFrom(ctx, types.StringType, endpoint.Events)
	return webhookEndpointModel{
		ID:             types.StringValue(endpoint.ID),
		URL:            types.StringValue(endpoint.URL),
		Name:           stringFromPointer(endpoint.Name),
		Format:         types.StringValue(endpoint.Format),
		Events:         events,
		Enabled:        types.BoolValue(endpoint.Enabled),
		Secret:         types.StringValue(endpoint.Secret),
		OrganizationID: types.StringValue(endpoint.OrganizationID),
		CreatedAt:      types.StringValue(endpoint.CreatedAt),
	}
}

func eventsToAPI(ctx context.Context, events types.List) ([]string, diag.Diagnostics) {
	var result []string
	diags := events.ElementsAs(ctx, &result, false)
	return result, diags
}
