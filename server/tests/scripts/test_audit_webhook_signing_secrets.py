import base64
import binascii
import secrets

import pytest
from standardwebhooks.webhooks import EmptyWebhookSecretError
from standardwebhooks.webhooks import Webhook as StandardWebhook

from polar.kit.crypto import generate_token
from polar.webhook.constants import WEBHOOK_SECRET_PREFIX
from scripts.audit_webhook_signing_secrets import (
    EmptyKey,
    InvalidStandardSecret,
    NotBase64,
    validate_secret,
)


def polar_secret(key_bytes: int) -> str:
    encoded = base64.b64encode(secrets.token_bytes(key_bytes)).decode()
    return f"{WEBHOOK_SECRET_PREFIX}{encoded}"


# Every one of these produces a signature a spec verifier accepts, however
# unlike a generated secret it looks.
SIGNABLE = [
    pytest.param(polar_secret(32), id="generated by Polar"),
    pytest.param(
        generate_token(prefix=WEBHOOK_SECRET_PREFIX),
        id="issued by Polar before the cutoff",
    ),
    pytest.param(polar_secret(8), id="key shorter than the spec recommends"),
    pytest.param(polar_secret(65), id="key longer than the spec recommends"),
    pytest.param(polar_secret(32).rstrip("="), id="base64 left unpadded"),
    pytest.param("mysupersecretwebhookkey123456789", id="passphrase without a prefix"),
    pytest.param(
        f"{WEBHOOK_SECRET_PREFIX}polar$$secret$$b64", id="characters the decoder drops"
    ),
]

# No key can be derived from these, so signing raises before delivery.
UNSIGNABLE = [
    pytest.param(
        "polar_wh_secret_1234567890abcdef", NotBase64, id="undecodable length"
    ),
    pytest.param("", EmptyKey, id="empty secret"),
    pytest.param(WEBHOOK_SECRET_PREFIX, EmptyKey, id="prefix and nothing else"),
]


class TestValidateSecret:
    @pytest.mark.parametrize("secret", SIGNABLE)
    def test_signable(self, secret: str) -> None:
        validate_secret(secret)
        StandardWebhook(secret)

    @pytest.mark.parametrize(("secret", "expected"), UNSIGNABLE)
    def test_unsignable(
        self, secret: str, expected: type[InvalidStandardSecret]
    ) -> None:
        with pytest.raises(expected):
            validate_secret(secret)
        with pytest.raises((binascii.Error, EmptyWebhookSecretError)):
            StandardWebhook(secret)
